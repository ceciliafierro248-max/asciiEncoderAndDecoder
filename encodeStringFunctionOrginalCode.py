def encodeString(stringVal):
    prevChar = stringVal[0]
    number = 0
    encodeList = []
    for char in stringVal:
        if char != prevChar:
            if char is not None:
                encodeList.append((prevChar, number))
            number = 1
            prevChar = char
        else:
            number = number + 1

    encodeList.append((prevChar, number))

    return encodeList
